#!/usr/bin/env node
/**
 * Replay runner.
 *
 * `--dry-run` supplies the **recorded transport**; `--live` supplies the real
 * Anthropic client. That is the only difference between the two invocations —
 * the tool loop, the tools, the prompt and the report writer are identical, and
 * in both modes the tools really do read the real cluster (read-only, as
 * `kube-system:sre-agent-ro`). See `src/transport.ts`.
 */

import { PublicationRejectedError } from "../src/publication.js";
import { formatGrade } from "../src/grade.js";
import { runReplay } from "../src/replay.js";
import { isCandidatePath, listScenarioIds } from "../src/scenario.js";
import { describeTransportFailure, type TransportKind } from "../src/transport.js";

const USAGE = `sre-agent replay — drive a scenario end to end through the real tool loop

Usage:
  npm run replay -- --scenario <id> [--dry-run | --live | --local] [--out <dir>] [--no-grade]
  npm run replay -- --list

Modes:
  --dry-run   (default) recorded assistant turns, no network, no API key.
              Real tools still run against the real cluster, read-only.
  --live      real Anthropic API. Requires ANTHROPIC_API_KEY.
  --local     real local model over an OpenAI-compatible endpoint.
              Requires LOCAL_MODEL_BASE_URL + LOCAL_MODEL_NAME. No Anthropic
              key; nothing leaves the LAN.

Scenarios: ${listScenarioIds().join(", ")}
`;

function argValue(argv: readonly string[], flag: string): string | undefined {
  const index = argv.indexOf(flag);
  if (index === -1) return undefined;
  return argv[index + 1];
}

async function main(argv: readonly string[]): Promise<number> {
  if (argv.includes("--help") || argv.includes("-h")) {
    process.stdout.write(USAGE);
    return 0;
  }
  if (argv.includes("--list")) {
    process.stdout.write(`${listScenarioIds().join("\n")}\n`);
    return 0;
  }

  const scenarioId = argValue(argv, "--scenario") ?? argValue(argv, "-s");
  if (scenarioId === undefined) {
    process.stderr.write(`--scenario is required.\n\n${USAGE}`);
    return 64; // EX_USAGE
  }

  // Refuse a candidate here too, before a transport is chosen or a banner is
  // printed. `runReplay` is the authority — this is the
  // early, legible copy, so the operator gets the explanation instead of a
  // stack trace after the run has already announced itself.
  if (isCandidatePath(scenarioId)) {
    process.stderr.write(
      `${scenarioId} is a scenario CANDIDATE and cannot be replayed: candidate ` +
        "scripts are derived from the run's own calls and are not a recording. Grade it by " +
        "explicit path instead — npm run grade -- --scenario <dir> --report <dir>/answer-key.md\n",
    );
    return 64;
  }

  const selected = (["--live", "--local", "--dry-run"] as const).filter((f) =>
    argv.includes(f),
  );
  if (selected.length > 1) {
    process.stderr.write(`${selected.join(", ")} are mutually exclusive.\n`);
    return 64;
  }
  const kind: TransportKind = argv.includes("--live")
    ? "live"
    : argv.includes("--local")
      ? "local"
      : "recorded";

  const outDir = argValue(argv, "--out");

  const banner = {
    live: "LIVE — real Anthropic model",
    local: "LOCAL — real local model, no Anthropic key",
    recorded: "DRY RUN — recorded assistant turns",
  }[kind];
  process.stderr.write(`replaying ${scenarioId} (${banner})\n`);

  const result = await runReplay({
    scenarioId,
    transportKind: kind,
    ...(outDir === undefined ? {} : { outputDir: outDir }),
    onTurn: (line) => process.stderr.write(`${line}\n`),
  });

  process.stderr.write(
    `\ntransport: ${result.transport.describe()}\n` +
      `report:    ${result.triage.reportPath}\n` +
      `transcript:${result.transcriptPath}\n` +
      `retrieval: ${result.retrievalPath}\n` +
      `queries:   ${result.queriesPath}\n` +
      `turns:     ${result.triage.turns} (stop_reason=${result.triage.stopReason ?? "unknown"})\n\n`,
  );

  if (!argv.includes("--no-grade")) {
    process.stdout.write(`${formatGrade(result.grade)}\n`);
    if (kind === "recorded") {
      process.stdout.write(
        "\nNOTE: this grade scores a RECORDED report. It proves the harness and " +
          "the grader, not the model. Root-cause quality stays UNPROVEN until " +
          "the same command runs with --live or --local.\n",
      );
    } else if (kind === "local") {

      process.stdout.write(
        `\nNOTE: this grade scores a report generated by the local model ` +
          `\`${result.transport.config.ANTHROPIC_TRIAGE_MODEL}\`. It speaks to the ` +
          "local-model acceptance bars for that model only — never for a class of " +
          "models, and never for the frontier models.\n",
      );
    }
    // 0 only for a CLEAN pass; qualified passes exit 2 so automation cannot
    // read an excused grade as an unexcused one.
    return result.grade.verdict === "PASS"
      ? 0
      : result.grade.verdict === "FAIL"
        ? 1
        : 2;
  }

  process.stdout.write(`${result.triage.reportPath}\n`);
  return 0;
}

await main(process.argv.slice(2)).then(
  (code) => {
    process.exitCode = code;
  },
  (error: unknown) => {
    // Not `error.message`: the SDK re-throws anything the transport throws as
    // `APIConnectionError("Connection error.")` with the real reason on
    // `.cause`. See `describeTransportFailure`.
    process.stderr.write(`${describeTransportFailure(error)}\n`);
    process.exitCode = error instanceof PublicationRejectedError ? error.exitCode : 1;
  },
);
